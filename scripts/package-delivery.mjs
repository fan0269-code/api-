import { mkdir, rm, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(fileURLToPath(new URL('..', import.meta.url)));
const releaseDir = join(root, 'release');
const packageRoot = join(releaseDir, 'relayhub-api-relay-console');
const archivePath = join(releaseDir, 'relayhub-api-relay-console.tar.gz');

const requiredPaths = [
  'dist/index.html',
  'README.md',
  'deploy/tencent-cloud/README.md',
  'deploy/tencent-cloud/deploy.sh',
  'deploy/tencent-cloud/nginx-api-relay-console.conf',
  'deploy/tencent-cloud/.env.example'
];

for (const path of requiredPaths) {
  if (!existsSync(join(root, path))) {
    throw new Error(`Missing required delivery file: ${path}`);
  }
}

await rm(packageRoot, { recursive: true, force: true });
await mkdir(packageRoot, { recursive: true });

const copy = (from, to) => {
  const result = spawnSync('cp', ['-R', from, to], { cwd: root, stdio: 'inherit' });
  if (result.status !== 0) {
    throw new Error(`Failed to copy ${from}`);
  }
};

copy('dist', join(packageRoot, 'dist'));
copy('README.md', join(packageRoot, 'README.md'));
copy('deploy/tencent-cloud', join(packageRoot, 'tencent-cloud'));

await writeFile(
  join(packageRoot, 'DELIVERY.md'),
  `# Delivery Package

This package contains the production static site and Tencent Cloud deployment assets.

## Contents

- dist/: production static files generated by Vite.
- README.md: project overview and acceptance commands.
- tencent-cloud/: deployment script, Nginx config, and environment template.

## Quick Deploy

1. Copy tencent-cloud/.env.example to tencent-cloud/.env.local and fill in the server values.
2. Upload dist/ to your web root, or use the deployment script from the source repository.
3. Configure Nginx with tencent-cloud/nginx-api-relay-console.conf.
`,
  'utf8'
);

await rm(archivePath, { force: true });

const tar = spawnSync('tar', ['-czf', archivePath, '-C', releaseDir, 'relayhub-api-relay-console'], {
  cwd: root,
  stdio: 'inherit'
});

if (tar.status !== 0) {
  throw new Error('Failed to create delivery archive');
}

console.log(`Created ${archivePath}`);
