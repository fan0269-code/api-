import { mkdir, rm, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(fileURLToPath(new URL('..', import.meta.url)));
const releaseDir = join(root, 'release');
const packageRoot = join(releaseDir, 'sub2api-admin-console');
const archivePath = join(releaseDir, 'sub2api-admin-console.tar.gz');

const requiredPaths = [
  'dist/index.html',
  'README.md',
  'package.json',
  'docs/API.md',
  'docs/ARCHITECTURE.md',
  'docs/DELIVERY.md',
  'deploy/tencent-cloud/README.md',
  'deploy/tencent-cloud/deploy.sh',
  'deploy/tencent-cloud/docker-compose.yml',
  'deploy/tencent-cloud/nginx-api-relay-console.conf',
  'deploy/tencent-cloud/.env.example'
];

for (const path of requiredPaths) {
  if (!existsSync(join(root, path))) {
    throw new Error(`Missing required delivery file: ${path}`);
  }
}

await rm(packageRoot, { recursive: true, force: true });
await mkdir(packageRoot, { recursive: true });

const copy = (from, to) => {
  const result = spawnSync('cp', ['-R', from, to], { cwd: root, stdio: 'inherit' });
  if (result.status !== 0) {
    throw new Error(`Failed to copy ${from}`);
  }
};

copy('dist', join(packageRoot, 'dist'));
copy('README.md', join(packageRoot, 'README.md'));
copy('package.json', join(packageRoot, 'package.json'));
await mkdir(join(packageRoot, 'docs'), { recursive: true });
copy('docs/API.md', join(packageRoot, 'docs', 'API.md'));
copy('docs/ARCHITECTURE.md', join(packageRoot, 'docs', 'ARCHITECTURE.md'));
copy('docs/DELIVERY.md', join(packageRoot, 'docs', 'DELIVERY.md'));
copy('deploy/tencent-cloud', join(packageRoot, 'tencent-cloud'));

await writeFile(
  join(packageRoot, 'DELIVERY.md'),
  `# sub2api Admin Console Delivery Package

This package contains the React admin console build and Tencent Cloud Docker Compose deployment assets for sub2api.

## Contents

- dist/: production static files generated by Vite.
- tencent-cloud/docker-compose.yml: sub2api, PostgreSQL, and Redis services.
- tencent-cloud/nginx-api-relay-console.conf: Nginx static frontend and /api + /v1 reverse proxy.
- tencent-cloud/.env.example: required production environment variables.
- docs/: API, architecture, and delivery documentation.

## Quick Deploy

1. Copy tencent-cloud/.env.example to tencent-cloud/.env and fill in strong secrets.
2. Upload this package to /var/www/api-relay-console on the Tencent Cloud CVM.
3. Run: docker compose --env-file .env up -d
4. Copy nginx-api-relay-console.conf to /etc/nginx/conf.d/ and reload Nginx.
5. Open the domain and log in with ADMIN_EMAIL / ADMIN_PASSWORD.
`,
  'utf8'
);

await rm(archivePath, { force: true });

const tar = spawnSync('tar', ['-czf', archivePath, '-C', releaseDir, 'sub2api-admin-console'], {
  cwd: root,
  stdio: 'inherit'
});

if (tar.status !== 0) {
  throw new Error('Failed to create delivery archive');
}

console.log(`Created ${archivePath}`);
